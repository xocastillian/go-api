-- ===========================================================================
-- pgbench_login.sql — pgbench-скрипт, имитирующий SQL-нагрузку ЛОГИНА.
--
-- Один "транзакционный" цикл pgbench = этот скрипт. Он повторяет именно
-- тот запрос, который делает repository.GetByEmail при login (совпадение
-- по форме критично: индекс у нас на lower(email), и запрос должен его
-- ТРОНУТЬ — запрос на голый email индекс проигнорировал бы).
--
-- \set u random(...) — pgbench-переменная: случайный индекс юзера на
-- каждый цикл, чтобы каждый запрос искал РАЗНЫЕ строки (реалистично),
-- а не один и тот же закэшированный.
-- ===========================================================================
\set u random(1, 100000)
SELECT id, password_hash FROM users WHERE lower(email) = lower('bench' || :u || '@bench.dev');