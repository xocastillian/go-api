-- ===========================================================================
-- pgbench_seed.sql — сид данных для нагрузочного теста БД.
--
-- Запускается только в bench_db (изолированная копия схемы, см. make
-- load-setup). 100k юзеров имитируют прод-объём: на пустой таблице
-- бенчмарк врёт — seq scan по 3 строкам "мгновенен" без всякого индекса.
--
-- Про password_hash: это НЕ настоящий bcrypt — тест только SELECT'ит
-- значение, ни один запрос его не проверяет. Настоящий bcrypt на 100k
-- строк занял бы часы чисто ради бенчмарка. Заполняем фейковой строкой.
--
-- Идемпотентность: INSERT сработает только если юзеров ещё нет
-- (guard по bench1@bench.dev) — повторный запуск не задублирует данные.
-- ===========================================================================
INSERT INTO users (email, password_hash, role)
SELECT 'bench' || g || '@bench.dev',
       'fake-bcrypt-hash-benchmark-only',
       'user'
FROM generate_series(1, 100000) g
WHERE NOT EXISTS (SELECT 1 FROM users WHERE email = 'bench1@bench.dev');