// Package user инкапсулирует ВСЁ, что относится к пользователям:
// доменную модель, репозиторий (БД), сервис (бизнес-логику),
// HTTP-хендлер, DTO и роуты.
//
// Это "Package by Feature": одна фича — один пакет, а слои внутри неё —
// отдельные файлы. Так весь код по фиче лежит рядом, и нет кучи
// крошечных пакетов с одинаковым именем (repository/user, service/user, ...).
package user

import (
	"time"

	"github.com/google/uuid"
)

// Role — роль пользователя.
// Отдельный тип, а не голый string: компилятор не даст передать
// произвольную строку туда, где ожидается роль, и поймает опечатки.
type Role string

// Допустимые роли. Значения совпадают с CHECK-констрейнтом в БД
// (db/migrations/00001_init.sql), чтобы Go и Postgres говорили на одном языке.
const (
	RoleUser  Role = "user"
	RoleAdmin Role = "admin"
)

// User — сущность пользователя. Это "чистая" доменная модель:
// она ничего не знает ни про gin, ни про pgx, ни про JSON.
// Её задача — описывать данные предметной области, и только.
type User struct {
	ID           uuid.UUID // уникальный идентификатор (генерируется БД)
	Email        string    // логин/почта, уникальна
	PasswordHash string    // ВСЕГДА хеш, никогда не открытый пароль
	Role         Role      // user или admin
	CreatedAt    time.Time // время создания (TIMESTAMPTZ в БД)
	UpdatedAt    time.Time // время последнего изменения
}
