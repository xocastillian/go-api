package postgres

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

// DBTX — минимальный набор методов, который нужен репозиториям для работы с БД.
//
// Зачем интерфейс, а не *pgxpool.Pool напрямую:
//   - и *pgxpool.Pool, и pgx.Tx (транзакция) реализуют эти методы
//     с ОДИНАКОВЫМИ сигнатурами. Значит репозиторий, написанный против DBTX,
//     одинаково работает и с пулом (обычная работа сервера), и с транзакцией
//     (интеграционные тесты, атомарные операции) — без единой правки кода.
//   - в интеграционных тестах мы подсуём сюда транзакцию, а в конце откатим её:
//     данные теста не осядут в БД. Транзакцию даёт pgxpool.Pool.Begin(ctx).
//
// Интерфейс объявлен в общем инфраструктурном пакете, потому что у него
// НЕСКОЛЬКО потребителей (все репозитории: user, auth, notes...). Держать
// его в каждом пакете значило бы дублировать одну и ту же декларацию.
//
// Сигнатуры взяты один в один из pgx v5, чтобы и *pgxpool.Pool, и pgx.Tx
// удовлетворяли интерфейсу СТРУКТУРНО (Go проверяет это по сигнатурам,
// без явного "implements").
type DBTX interface {
	// Begin открывает новую транзакцию и возвращает её как pgx.Tx.
	//
	// Добавлен, чтобы репозитории могли исполнять НЕСКОЛЬКО запросов
	// атомарно (см. auth.Repository.WithTx): "отозвать старое + создать
	// новое" обязаны либо исполниться вместе, либо откатиться вместе.
	//
	// Тонкость: Begin есть и у ПУЛА, и у САМОЙ транзакции pgx.Tx.
	// У транзакции он открывает ВЛОЖЕННУЮ транзакцию (under the hood —
	// SAVEPOINT): коммит вложенной лишь "снимает" savepoint, а общий
	// итог решает внешний Commit/Rollback. Поэтому DBTX с Begin
	// корректно работает, даже если репозиторий уже сидит на транзакции.
	Begin(ctx context.Context) (pgx.Tx, error)

	// Exec — для запросов без возвращаемых строк (INSERT/UPDATE/DELETE).
	// Возвращает CommandTag, из которого берут RowsAffected.
	Exec(ctx context.Context, sql string, arguments ...any) (pgconn.CommandTag, error)

	// Query — для запросов, возвращающих МНОГО строк (SELECT со списком).
	// Возвращает итератор Rows, по которому идём rows.Next().
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)

	// QueryRow — для запросов, возвращающих РОВНО одну строку
	// (SELECT ... WHERE id = $1, INSERT ... RETURNING).
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}
