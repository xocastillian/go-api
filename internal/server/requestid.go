// requestid.go — middleware, выдающий каждому запросу уникальный ID.
//
// Зачем вообще ID запроса:
//   - ОДИН запрос проходит десятки слоёв: middleware, хендлер, сервис,
//     репозиторий, БД. Каждый из них может что-то залогировать. Без общего
//     ID строки в логах невозможно связать: "какой из тысячи POST /auth/login
//     упал с 500 и почему?".
//   - С ID весь путь запроса собирается одной командой:
//     `grep request_id=<id> logs.txt` — и перед глазами вся история.
//   - ID возвращается клиенту в заголовке X-Request-Id. Пользователь жалуется
//     "вот эта ошибка была в 12:03" — он присылает ID из заголовка, и ты
//     находишь ровно его запрос. Это стандарт индустрии (так делают AWS,
//     Cloudflare, почти все API).
//
// Внимание: это НЕ трейсинг из OpenTelemetry (там trace_id, span'ы,
// экспорт в collector). Это его легковесный предшественник, которого
// достаточно для сервиса без распределённых вызовов.
package server

import (
	"github.com/gin-gonic/gin"
	"github.com/google/uuid"
)

// RequestIDHeader — заголовок, через который ID уходит клиенту И приходит
// от клиента. Экспортируем (заглавная буква), чтобы тесты и, возможно,
// другие middleware ссылались на константу, а не копировали строку.
const RequestIDHeader = "X-Request-Id"

// ctxRequestIDKey — ключ, под которым ID лежит в контексте gin.
// Префикс "server." — та же защита от коллизий, что и "auth." в middleware.go:
// контекст gin — это map[string]any, и любой пакет может туда писать.
// Достать значение можно через RequestIDOf(c).
const ctxRequestIDKey = "server.request_id"

// maxRequestIDLen — потолок длины КЛИЕНТСКОГО ID (см. ниже, почему он нужен).
const maxRequestIDLen = 64

// RequestID — middleware: гарантирует, что у каждого запроса есть ID.
//
// Источник ID — по приоритету:
//  1. Заголовок X-Request-Id от клиента (если он пришёл корректный).
//     Зачем доверять клиенту: сервисы часто стоят цепочкой (gateway → api).
//     Gateway уже сгенерировал свой ID — если мы перезатрём его своим,
//     логи gateway и api нельзя будет сопоставить. Поэтому чужой ID
//     принимаем и передаём дальше.
//  2. Если заголовка нет или он не прошёл проверку — генерируем свой UUID.
func RequestID() gin.HandlerFunc {
	return func(c *gin.Context) {
		id := c.GetHeader(RequestIDHeader)

		// Клиентский ID принимаем только после проверки (см. validRequestID):
		// слишком длинный или с управляющими символами — игнорируем и
		// подменяем своим. В боевом режиме это защита от двух атак:
		//   - log injection: атакующий шлёт заголовок "id\n2025-01-01 ERROR ..."
		//     и в логах появляется фейковая строка, которой не было;
		//   - раздувание логов: заголовок на мегабайт дублируется в каждую строку.
		if !validRequestID(id) {
			id = uuid.NewString()
		}

		// Кладём в контекст — отсюда ID достанут Logger (и другие middleware)
		// через RequestIDOf(c), даже не зная, откуда он взялся.
		c.Set(ctxRequestIDKey, id)

		// Отдаём ID клиенту в ответе. ВАЖНО: ставим заголовок ДО c.Next(),
		// иначе хендлеры, начавшие писать ответ, "закроют" заголовки, и
		// клиент его не получит.
		c.Writer.Header().Set(RequestIDHeader, id)

		c.Next()
	}
}

// RequestIDOf достаёт ID запроса из контекста (после middleware RequestID).
// Паттерн доступа — тот же, что auth.UserID: безопасное приведение типа,
// при промахе вернётся пустая строка. Промах возможен, только если ручку
// повесили на роутер без RequestID — это заметно в логах отсутствием поля.
func RequestIDOf(c *gin.Context) string {
	v, _ := c.Get(ctxRequestIDKey)
	id, _ := v.(string)
	return id
}

// validRequestID проверяет, что клиентский ID безопасно принимать.
//
// Правила:
//   - непустой и не длиннее maxRequestIDLen байт (наш UUID — 36 символов,
//     этого хватает любому осмысленному correlation id);
//   - только printable ASCII без пробела (символы от '!' до '~').
//
// Почему именно так: запрещаем ВСЁ, кроме явно разрешённого ("запрещено
// всё, что не разрешено явно" — тот же принцип, что в CORS). Пробел и
// переводы строк не разрешены — значит, атака log injection не проходит.
func validRequestID(id string) bool {
	if id == "" || len(id) > maxRequestIDLen {
		return false
	}
	for _, r := range id {
		// Диапазон '!'..'~' — весь печатный ASCII минус пробел.
		// Управляющие символы (\n, \r, \t, \x00) и всё не-ASCII сюда не попадают.
		if r < '!' || r > '~' {
			return false
		}
	}
	return true
}
